//! The JSON messages exchanged over `GET /api/v1/support/ws`. Every message is
//! a text frame holding one object with a `type` field.

use std::sync::Arc;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::models::{SupportConversationRow, SupportMessage};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ChatRole {
    User,
    Admin,
}

impl ChatRole {
    pub fn as_str(self) -> &'static str {
        match self {
            ChatRole::User => "user",
            ChatRole::Admin => "admin",
        }
    }

    pub fn other(self) -> ChatRole {
        match self {
            ChatRole::User => ChatRole::Admin,
            ChatRole::Admin => ChatRole::User,
        }
    }
}

/// Client → server.
#[derive(Debug, Clone, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ClientEvent {
    /// Users omit `conversation_id`: their single conversation is created or
    /// reopened on the first send. Admins must name the conversation.
    SendMessage {
        conversation_id: Option<Uuid>,
        body: String,
        /// Generated by the sender; a resend with the same id is not stored twice.
        client_msg_id: String,
    },
    Typing {
        conversation_id: Option<Uuid>,
        is_typing: bool,
    },
    MarkRead {
        conversation_id: Option<Uuid>,
    },
    Ping,
    // ── admin only ──
    JoinConversation {
        conversation_id: Uuid,
    },
    LeaveConversation {
        conversation_id: Uuid,
    },
    CloseConversation {
        conversation_id: Uuid,
    },
    ReopenConversation {
        conversation_id: Uuid,
    },
    AssignToMe {
        conversation_id: Uuid,
    },
}

impl ClientEvent {
    pub fn is_admin_only(&self) -> bool {
        matches!(
            self,
            ClientEvent::JoinConversation { .. }
                | ClientEvent::LeaveConversation { .. }
                | ClientEvent::CloseConversation { .. }
                | ClientEvent::ReopenConversation { .. }
                | ClientEvent::AssignToMe { .. }
        )
    }
}

/// Server → client.
#[derive(Debug, Clone, Serialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerEvent {
    /// First frame after the upgrade: who the server thinks you are.
    Ready {
        user_id: Uuid,
        role: ChatRole,
        /// A user's conversation id, once they have one.
        conversation_id: Option<Uuid>,
    },
    Message {
        message: SupportMessage,
    },
    /// Your `send_message` is stored.
    Ack {
        client_msg_id: String,
        message_id: Uuid,
        conversation_id: Uuid,
        created_at: DateTime<Utc>,
        /// True when this `client_msg_id` had already been stored.
        duplicate: bool,
    },
    Typing {
        conversation_id: Uuid,
        user_id: Uuid,
        role: ChatRole,
        is_typing: bool,
    },
    /// The other side read everything up to now.
    Read {
        conversation_id: Uuid,
        by: ChatRole,
        at: DateTime<Utc>,
    },
    /// Inbox row changed (new message, read, status). Admins get every one;
    /// a user only gets their own. `total_unread` (admins only) is the unread
    /// count across all open conversations, for the nav badge.
    ConversationUpdated {
        conversation: Box<SupportConversationRow>,
        total_unread: Option<i64>,
    },
    /// Admins only: a user's first connection opened or last one closed.
    Presence {
        user_id: Uuid,
        online: bool,
    },
    Error {
        code: String,
        message: String,
        client_msg_id: Option<String>,
    },
    Pong,
}

impl ServerEvent {
    /// Serialise once; the hub shares the resulting frame between recipients.
    pub fn frame(&self) -> Arc<str> {
        match serde_json::to_string(self) {
            Ok(s) => Arc::from(s),
            // Cannot happen for these types; never panic on the hot path.
            Err(_) => Arc::from(r#"{"type":"error","code":"internal","message":"encode failed"}"#),
        }
    }

    pub fn error(code: &str, message: impl Into<String>) -> Self {
        ServerEvent::Error {
            code: code.to_string(),
            message: message.into(),
            client_msg_id: None,
        }
    }
}
